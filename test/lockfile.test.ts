import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  ProjectError,
  buildProjectContext,
  parseNpmLock,
  parsePnpmLock,
  parseYarnLock,
  readInstalledVersions,
} from '../src/project/index.js';

const deps = { react: '18.3.1', 'react-native': '^0.76.0', '@scope/native-lib': '~2.1.0' };

describe('parseNpmLock', () => {
  it('reads root node_modules entries from lockfileVersion 3', () => {
    const lock = {
      lockfileVersion: 3,
      packages: {
        '': { name: 'SampleApp' },
        'node_modules/react': { version: '18.3.1' },
        'node_modules/react-native': { version: '0.76.5' },
        'node_modules/@scope/native-lib': { version: '2.1.4' },
        'node_modules/other/node_modules/react-native': { version: '0.70.0' },
      },
    };
    expect(parseNpmLock(JSON.stringify(lock), deps)).toEqual({
      react: '18.3.1',
      'react-native': '0.76.5',
      '@scope/native-lib': '2.1.4',
    });
  });

  it('reads lockfileVersion 1 dependencies', () => {
    const lock = { lockfileVersion: 1, dependencies: { 'react-native': { version: '0.72.17' } } };
    expect(parseNpmLock(JSON.stringify(lock), deps)).toEqual({ 'react-native': '0.72.17' });
  });
});

describe('parseYarnLock', () => {
  it('reads Yarn classic lockfiles', () => {
    const lock = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@scope/native-lib@~2.1.0":
  version "2.1.4"
  resolved "https://registry.yarnpkg.com/@scope/native-lib/-/native-lib-2.1.4.tgz"

react-native@0.70.0:
  version "0.70.0"

react-native@^0.76.0:
  version "0.76.5"
  dependencies:
    react "18.3.1"

react@18.3.1, react@^18.0.0:
  version "18.3.1"
`;
    expect(parseYarnLock(lock, deps)).toEqual({
      react: '18.3.1',
      'react-native': '0.76.5',
      '@scope/native-lib': '2.1.4',
    });
  });

  it('reads Yarn Berry lockfiles', () => {
    const lock = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"@scope/native-lib@npm:~2.1.0":
  version: 2.1.4
  resolution: "@scope/native-lib@npm:2.1.4"

"react-native@npm:^0.76.0":
  version: 0.76.5
  resolution: "react-native@npm:0.76.5"

"react@npm:18.3.1, react@npm:^18.0.0":
  version: 18.3.1
  resolution: "react@npm:18.3.1"

"SampleApp@workspace:.":
  version: 0.0.0-use.local
  resolution: "SampleApp@workspace:."
`;
    expect(parseYarnLock(lock, deps)).toEqual({
      react: '18.3.1',
      'react-native': '0.76.5',
      '@scope/native-lib': '2.1.4',
    });
  });

  it('leaves out a package with several versions and no matching descriptor', () => {
    const lock = `react@17.0.2:
  version "17.0.2"

react@^18.0.0:
  version "18.3.1"
`;
    expect(parseYarnLock(lock, { react: '>=17' })).toEqual({});
  });

  it('rejects merge conflict markers', () => {
    expect(() => parseYarnLock('<<<<<<< HEAD\nreact@18.3.1:\n', deps)).toThrow(/merge conflict/);
  });
});

describe('parsePnpmLock', () => {
  it('reads lockfileVersion 9 importers and strips peer suffixes', () => {
    const lock = `lockfileVersion: '9.0'

importers:
  .:
    dependencies:
      react:
        specifier: 18.3.1
        version: 18.3.1
      react-native:
        specifier: ^0.76.0
        version: 0.76.5(@babel/core@7.25.2)(@types/react@18.3.12)(react@18.3.1)
    devDependencies:
      '@scope/native-lib':
        specifier: ~2.1.0
        version: link:../native-lib
`;
    expect(parsePnpmLock(lock, deps)).toEqual({ react: '18.3.1', 'react-native': '0.76.5' });
  });

  it('reads lockfileVersion 6 without importers', () => {
    const lock = `lockfileVersion: '6.0'

dependencies:
  react-native:
    specifier: ^0.76.0
    version: 0.76.5(@babel/core@7.25.2)(react@18.3.1)
`;
    expect(parsePnpmLock(lock, deps)).toEqual({ 'react-native': '0.76.5' });
  });

  it('reads lockfileVersion 5 string versions', () => {
    const lock = `lockfileVersion: 5.4

specifiers:
  react-native: ^0.71.0

dependencies:
  react-native: 0.71.19_@babel+core@7.20.0
`;
    expect(parsePnpmLock(lock, deps)).toEqual({ 'react-native': '0.71.19' });
  });
});

describe('readInstalledVersions', () => {
  let dir: string;

  beforeEach(async () => {
    dir = await mkdtemp(path.join(tmpdir(), 'rn-doctor-lock-'));
  });

  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it('returns {} when the lockfile is missing', async () => {
    expect(await readInstalledVersions(dir, 'yarn', { dependencies: deps })).toEqual({});
  });

  it('throws ProjectError for an unreadable lockfile', async () => {
    await writeFile(path.join(dir, 'package-lock.json'), '{ broken');
    await expect(readInstalledVersions(dir, 'npm', { dependencies: deps })).rejects.toThrow(ProjectError);
  });

  it('feeds the lockfile version into the project context', async () => {
    await writeFile(path.join(dir, 'package.json'), JSON.stringify({ dependencies: { 'react-native': '^0.76.0' } }));
    await writeFile(
      path.join(dir, 'package-lock.json'),
      JSON.stringify({ lockfileVersion: 3, packages: { 'node_modules/react-native': { version: '0.76.5' } } }),
    );
    expect(await buildProjectContext(dir)).toMatchObject({
      reactNativeVersion: '0.76.5',
      reactNativeVersionSource: 'lockfile',
      reactNativeRange: '^0.76.0',
      installed: { 'react-native': '0.76.5' },
    });
  });
});
